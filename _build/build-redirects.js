/* Builds .htaccess (Apache / LiteSpeed — what Hostinger runs) and _redirects
   (Netlify / Cloudflare, kept so the site can move hosts without redoing this).

   Every legacy URL answers 301, never 302. Cars that survived go to their new
   /coches/<slug>/; cars that left the fleet go to the brand page if the brand
   is still there, otherwise to /flota/. RewriteRule keeps the query string by
   default, so gclid and utm_* survive every one of these hops.

   Run: node _build/build-redirects.js */
