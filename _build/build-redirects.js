/* ?marca=<value> values that are not already a valid brand slug */
const MARCA = {
  mercedes: 'mercedes-amg', 'mercedes-benz': 'mercedes-amg', 'mercedes-amg': 'mercedes-amg',
  vw: 'volkswagen', volkswagen: 'volkswagen', 'range-rover': 'range-rover', 'land-rover': 'range-rover',
  porsche: 'porsche', lamborghini: 'lamborghini', audi: 'audi',
};
const MARCA_GONE = ['ferrari', 'bmw', 'mclaren', 'aston-martin', 'maserati', 'alfa-romeo', 'abarth', 'renault', 'motos'];

const rules = [];   // [from, to] for the plain-path redirects
Object.entries(CAR).forEach(([k, v]) => rules.push([`/alquiler-${k}-barcelona.html`, v]));
Object.entries(BRAND_HUB).forEach(([k, v]) => rules.push([`/alquiler-${k}-barcelona.html`, v]));
Object.entries(PAGE).forEach(([k, v]) => rules.push([`/${k}`, v]));

const esc = s => s.replace(/[.]/g, '\\.');

/* ---------- .htaccess ------------------------------------------------- */
const htaccess = `# =====================================================================
# SERRES DRIVE — .htaccess (Hostinger / LiteSpeed)
# Canonical host, ${rules.length} legacy-URL redirects + the ?marca= rules,
# branded 404 and cache policy. Generated by _build/build-redirects.js —
# edit that file, not this one.
#
# Every rule is 301. RewriteRule carries the query string through unless a
# substitution ends in "?", so gclid / utm_* survive the hop; the ?marca=
# block below rebuilds the query string by hand for the same reason.
# =====================================================================

RewriteEngine On
Options -MultiViews

# --- one canonical host: www -> apex ---------------------------------
RewriteCond %{HTTP_HOST} ^www\\.serresdrive\\.com$ [NC]
RewriteRule ^(.*)$ https://serresdrive.com/$1 [R=301,L]

# --- /index.html -> / -------------------------------------------------
# THE_REQUEST guard: only a direct request is redirected, never the
# internal rewrite DirectoryIndex performs (that would loop).
RewriteCond %{THE_REQUEST} \\s/index\\.html[?\\s] [NC]
RewriteRule ^index\\.html$ / [R=301,L]

# --- legacy ?marca= filter -> brand page ------------------------------
# The old catalogue filtered in place with /flota?marca=x. Those URLs are
# in paid ads, so they must land on the static brand page WITHOUT losing
# the click id. Most specific pattern first; %N is read from the LAST
# RewriteCond, which is why each case is written out in full.
${[
  /* The brand is written into the pattern as a literal, so it is NOT a
     capture group — the remaining %N are only the surrounding params.
     Getting this wrong silently ate the gclid on
     /flota?marca=porsche&gclid=…, which is the exact failure the brief
     calls out. Order matters: most specific pattern first. */
  { cond: '^(.+)&marca=BRAND&(.+)$', rest: '%1&%2' },   // params either side
  { cond: '^(.+)&marca=BRAND$',      rest: '%1'    },   // params before only
  { cond: '^marca=BRAND&(.+)$',      rest: '%1'    },   // params after only
  { cond: '^marca=BRAND$',           rest: ''      },   // marca alone
].map(({ cond, rest }) =>
  Object.entries(MARCA).map(([from, to]) =>
    `RewriteCond %{QUERY_STRING} ${cond.replace('BRAND', from)} [NC]\nRewriteRule ^flota/?$ /flota/${to}/?${rest} [R=301,L,NE]`
  ).concat(MARCA_GONE.map(from =>
    `RewriteCond %{QUERY_STRING} ${cond.replace('BRAND', from)} [NC]\nRewriteRule ^flota/?$ /flota/?${rest} [R=301,L,NE]`
  )).join('\n')
).join('\n')}

# --- legacy car detail: car.html?slug=X -> /coches/X/ ------------------
RewriteCond %{QUERY_STRING} ^slug=([a-zA-Z0-9-]+)$
RewriteRule ^car\\.html$ /coches/%1/? [R=301,L]
RewriteRule ^car\\.html$ /flota/? [R=301,L]

# --- legacy pages and car URLs (${rules.length}) ------------------------------------
${rules.map(([from, to]) => `RewriteRule ^${esc(from.slice(1))}$ ${to} [R=301,L]`).join('\n')}

# --- anything else that still looks like an old car page --------------
# A slug we never had 301s to the catalogue rather than into the 404, so a
# stale ad spends its click on the fleet instead of a dead end.
RewriteRule ^alquiler-[a-z0-9-]+-barcelona\\.html$ /flota/ [R=301,L]

# --- documentacion interna: nunca servirla -----------------------------
# "seo y google ads/" (plan de campanas, keywords, presupuestos, TZ) entro
# una vez en el repo por error. Se saco de git, pero el deploy de Hostinger
# NO borro la carpeta del servidor — los archivos con espacios en la ruta
# sobrevivieron a la sincronizacion. Se bloquea aqui para que deje de ser
# accesible; borrarla del servidor por hPanel sigue pendiente.
# "_build/" son los generadores: ninguna pagina los pide.
RewriteRule "^seo y google ads(/|$)" - [R=404,L]
RewriteRule "^_build(/|$)" - [R=404,L]

# --- fotos sueltas volcadas del movil ----------------------------------
# Las fotos nuevas llegan a la raiz del proyecto (IMG_2151.PNG y compania) y
# un "git add -A" las publico. Ya salieron del repo, pero el deploy de
# Hostinger tampoco las borro del disco — igual que con la carpeta de arriba.
# Su sitio es "Sicur Cars/<coche>/"; en la web no pinta nada un original de
# 1,4 MB con nombre de camara.
RewriteRule "^IMG_[0-9]+\.(png|jpe?g)$" - [R=404,L,NC]

# --- branded 404 -------------------------------------------------------
ErrorDocument 404 /404.html

# --- caching -----------------------------------------------------------
# Assets are requested with ?v= cache-busters (bumped on every deploy), so
# they can be immutable for a year. HTML/XML must revalidate so a deploy
# is visible immediately.
<IfModule mod_headers.c>
  <FilesMatch "\\.(css|js|jpg|jpeg|png|webp|avif|svg|ico|woff|woff2)$">
    Header set Cache-Control "public, max-age=31536000, immutable"
  </FilesMatch>
  <FilesMatch "\\.(html|xml|txt|json)$">
    Header set Cache-Control "no-cache"
  </FilesMatch>
</IfModule>

# --- compression -------------------------------------------------------
<IfModule mod_deflate.c>
  AddOutputFilterByType DEFLATE text/html text/css text/plain text/xml application/javascript application/json image/svg+xml
</IfModule>
`;
fs.writeFileSync(path.join(ROOT, '.htaccess'), htaccess);

/* ---------- _redirects (Netlify / Cloudflare) -------------------------- */
